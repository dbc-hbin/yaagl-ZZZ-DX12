using Sha256Digest = std::array<uint8_t, 32>;

inline bool sha256Matches(const uint8_t actual[32],
                          const Sha256Digest &expected) noexcept {
  return actual &&
         std::memcmp(actual, expected.data(), expected.size()) == 0;
}

